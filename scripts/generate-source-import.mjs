import { writeFile } from "node:fs/promises"
import { catskillsMikvahListings } from "../src/MikvahListings.ts"

const literal = (value) => `'${String(value).replaceAll("'", "''")}'`
const blocks = catskillsMikvahListings
  .map((item) => {
    const { sourceLabel, sourceUrl, ...details } = item.data
    return `
  if not exists(select 1 from public.listing_sources where source_key='mikvah.org' and external_id=${literal(item.id)}) then
    insert into public.listings(type,visibility) values('Mikvah','unpublished') returning id into lid;
    insert into public.listing_versions(listing_id,version_number,name,address,city,state,postal_code,map_location)
    values(lid,1,${[item.name, item.address, item.city, item.state, item.zip, item.mapLocation].map(literal).join(",")}) returning id into vid;
    insert into public.mikvah_details(version_id,details) values(vid,${literal(JSON.stringify(details))}::jsonb);
    insert into public.listing_sources(listing_id,source_key,external_id,label,url) values(lid,'mikvah.org',${literal(item.id)},${literal(sourceLabel)},${literal(sourceUrl)});
    update public.listing_versions set status='approved' where id=vid;
    update public.listings set published_version_id=vid,visibility='published' where id=lid;
    insert into public.review_events(listing_id,version_id,action,internal_note) values(lid,vid,'imported','Imported from the existing attributed directory. This is source attribution, not a new facility verification.');
  end if;`
  })
  .join("\n")
await writeFile(
  new URL(
    "../supabase/migrations/202610290002_import_directory.sql",
    import.meta.url,
  ),
  `-- Generated by scripts/generate-source-import.mjs. Repeatable; never overwrites reviewed records.
-- Source dates are not treated as facility verification dates. Sample Shuls are excluded.
begin;
do $import$ declare lid uuid; vid uuid; begin
${blocks}
end $import$;
commit;
`,
)
console.log(
  `Generated attributed import for ${catskillsMikvahListings.length} existing Mikvah records.`,
)
